export function thaiDigits(s) {
  return String(s).replace(/[0-9]/g, (d) => TH_DIGITS[Number(d)]);
}

export function timeAgo(lang, iso) {
  const t = STR[lang] || STR.th;
  const then = Date.parse(iso);
  if (!Number.isFinite(then)) return '';
  const sec = Math.max(0, (Date.now() - then) / 1000);
  if (sec < 60) return t.justNow;
  const m = Math.floor(sec / 60);
  if (m < 60) return t.minAgo(m);
  const h = Math.floor(m / 60);
  if (h < 24) return t.hourAgo(h);
  return t.dayAgo(Math.floor(h / 24));
}
